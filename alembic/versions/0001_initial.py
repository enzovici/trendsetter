CAGG_TEMPLATE = """
CREATE MATERIALIZED VIEW IF NOT EXISTS {name}
WITH (timescaledb.continuous) AS
SELECT
    time_bucket(INTERVAL '{bucket}', bucket_start) AS bucket_start,
    entity_id,
    sum(new_mentions) AS new_mentions,
    sum(observations) AS observations,
    sum(views_sum) AS views_sum,
    sum(likes_sum) AS likes_sum,
    sum(author_count) AS author_count
FROM entity_stats_15m
GROUP BY 1, 2
WITH NO DATA
"""


